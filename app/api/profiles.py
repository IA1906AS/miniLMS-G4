"""Private profile editing and course-scoped public member profiles."""

import io
import secrets
import warnings
from pathlib import Path

from flask import Blueprint, current_app, g, jsonify, request, send_file
from PIL import Image, ImageOps, UnidentifiedImageError
from werkzeug.exceptions import RequestEntityTooLarge

from app.api.audit import write_audit
from app.api.errors import Forbidden, NotFound, ValidationError
from app.api.services import list_courses

bp = Blueprint("profiles", __name__)
MAX_AVATAR_BYTES = 2 * 1024 * 1024
MAX_AVATAR_PIXELS = 16_000_000


@bp.after_request
def private_response(response):
    response.headers["Cache-Control"] = "private, no-store"
    return response


def _store():
    return current_app.extensions["lms_store"]


def _field(user, name):
    return user.get(name, "") if isinstance(user, dict) else getattr(user, name)


def _user(user_id):
    store = _store()
    user = store.get_user(user_id)
    if user is None:
        raise NotFound()
    return user


def _profile(user, *, private=False):
    user_id = _field(user, "id")
    result = {
        "id": user_id,
        "fullName": _field(user, "full_name"),
        "bio": _field(user, "bio"),
        "role": _field(user, "role"),
        "avatarUrl": f"/users/{user_id}/avatar"
        if _field(user, "avatar_filename")
        else None,
    }
    if private:
        result.update(email=_field(user, "email"), contact=_field(user, "contact"))
    return result


def _member_ids(course):
    store = _store()
    course_id = course["id"]
    students = {item.student_id for item in store.list_enrollments(course_id)}
    return students | {course["instructorId"]}


def _check_profile_access(user_id):
    if g.actor["id"] == user_id or g.actor["role"] == "ADMIN":
        return
    for course in list_courses(store=_store()):
        members = _member_ids(course)
        if {g.actor["id"], user_id} <= members:
            return
    raise Forbidden()


def _update(changes):
    store = _store()
    return store.update_profile(g.actor["id"], changes)


def _audit(action):
    write_audit(
        actor_id=g.actor["id"],
        action=action,
        resource=request.path,
        result="SUCCESS",
    )


@bp.get("/me/profile")
def my_profile():
    return jsonify(_profile(_user(g.actor["id"]), private=True))


@bp.put("/me/profile")
def update_profile():
    data = request.get_json(silent=True)
    fields = {
        "fullName": ("full_name", 120),
        "bio": ("bio", 2000),
        "contact": ("contact", 500),
    }
    if not isinstance(data, dict) or not data or set(data) - fields.keys():
        raise ValidationError()
    changes = {}
    for key, value in data.items():
        column, limit = fields[key]
        if not isinstance(value, str) or len(value) > limit or "\x00" in value:
            raise ValidationError()
        changes[column] = value.strip()
    _update(changes)
    _audit("UPDATE_PROFILE")
    return jsonify(_profile(_user(g.actor["id"]), private=True))


@bp.get("/me/courses")
def my_courses():
    courses = list_courses(store=_store())
    return jsonify(
        [
            course
            for course in courses
            if g.actor["role"] == "ADMIN" or g.actor["id"] in _member_ids(course)
        ]
    )


@bp.get("/courses/<course_id>/members")
def course_members(course_id):
    course = next(
        (item for item in list_courses(store=_store()) if item["id"] == course_id),
        None,
    )
    if course is None:
        raise NotFound()
    members = _member_ids(course)
    if g.actor["role"] != "ADMIN" and g.actor["id"] not in members:
        raise Forbidden()
    return jsonify([_profile(_user(user_id)) for user_id in sorted(members)])


@bp.get("/users/<user_id>/profile")
def member_profile(user_id):
    _check_profile_access(user_id)
    return jsonify(_profile(_user(user_id)))


def _avatar_path(filename):
    # Stored names are generated by the server, never supplied by the client.
    if len(filename) != 36 or not filename.endswith(".png"):
        raise NotFound()
    if any(char not in "0123456789abcdef" for char in filename[:-4]):
        raise NotFound()
    return Path(current_app.config["AVATAR_UPLOAD_DIR"]) / filename


def _remove_avatar(user):
    filename = _field(user, "avatar_filename")
    if filename:
        _avatar_path(filename).unlink(missing_ok=True)


@bp.post("/me/avatar")
def upload_avatar():
    # Limit the multipart body as well as the decoded image dimensions.
    request.max_content_length = MAX_AVATAR_BYTES + 64 * 1024
    if set(request.files) != {"avatar"}:
        raise ValidationError()
    content = request.files["avatar"].read(MAX_AVATAR_BYTES + 1)
    if len(content) > MAX_AVATAR_BYTES:
        raise RequestEntityTooLarge()
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(content)) as source:
                if source.format not in {"JPEG", "PNG", "WEBP"}:
                    raise ValidationError()
                if source.width * source.height > MAX_AVATAR_PIXELS:
                    raise ValidationError()
                source.load()
                image = ImageOps.exif_transpose(source).convert("RGBA")
                image.thumbnail((512, 512))
                # Re-encode pixels only; discard EXIF and other uploaded metadata.
                clean = Image.new("RGBA", image.size)
                clean.paste(image)
                output = io.BytesIO()
                clean.save(output, format="PNG")
    except (
        UnidentifiedImageError,
        OSError,
        ValueError,
        Image.DecompressionBombWarning,
        Image.DecompressionBombError,
    ) as exc:
        raise ValidationError() from exc
    filename = f"{secrets.token_hex(16)}.png"
    path = _avatar_path(filename)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as file:
        file.write(output.getvalue())
    try:
        previous = _update({"avatar_filename": filename})
    except Exception:
        path.unlink(missing_ok=True)
        raise
    _remove_avatar(previous)
    _audit("UPDATE_AVATAR")
    return jsonify(_profile(_user(g.actor["id"]), private=True))


@bp.delete("/me/avatar")
def delete_avatar():
    previous = _update({"avatar_filename": ""})
    _remove_avatar(previous)
    _audit("DELETE_AVATAR")
    return jsonify(_profile(_user(g.actor["id"]), private=True))


@bp.get("/users/<user_id>/avatar")
def get_avatar(user_id):
    _check_profile_access(user_id)
    filename = _field(_user(user_id), "avatar_filename")
    if not filename:
        raise NotFound()
    path = _avatar_path(filename)
    try:
        content = path.read_bytes()
    except FileNotFoundError as exc:
        raise NotFound() from exc
    # Close the disk file before serving so replacement also works on Windows.
    response = send_file(io.BytesIO(content), mimetype="image/png", conditional=False)
    response.headers["Cache-Control"] = "private, no-store"
    return response
