    # ========================================================
    # INITIALIZATION
    # ========================================================

    def __init__(self, database_url: str, *, schema: str = "public") -> None:
        if not database_url:
            raise RuntimeError("DATABASE_URL is required")
        if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", schema):
            raise ValueError("Invalid PostgreSQL schema name")
        self.database_url = database_url
        self.schema = schema
        with self._connect() as conn:
            # Serialize schema setup across workers that start simultaneously.
            conn.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                ("minilms:schema:" + schema,),
            )
            conn.execute(
                sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema))
            )
            for statement in _SCHEMA.split(";"):
                if statement.strip():
                    conn.execute(statement)
            conn.execute(
                "ALTER TABLE enrollments ADD COLUMN IF NOT EXISTS "
                "version INTEGER NOT NULL DEFAULT 0"
            )
            for column in (
                "token_version",
                "full_name",
                "bio",
                "contact",
                "avatar_filename",
                "is_locked",
            ):
                definition = (
                    "BOOLEAN NOT NULL DEFAULT FALSE"
                    if column == "is_locked"
                    else (
                        "INTEGER NOT NULL DEFAULT 0"
                        if column == "token_version"
                        else "TEXT NOT NULL DEFAULT ''"
                    )
                )
                conn.execute(
                    sql.SQL(
                        "ALTER TABLE users ADD COLUMN IF NOT EXISTS {} " + definition
                    ).format(sql.Identifier(column))
                )

    @contextmanager
    def _connect(self):
        # psycopg commits on success, rolls back on failure and closes the connection.
        with psycopg.connect(
            self.database_url, row_factory=dict_row, connect_timeout=10
        ) as conn:
            conn.execute("SELECT set_config('search_path', %s, false)", (self.schema,))
            yield conn

    # ========================================================
    # SEED DATA
    # ========================================================

    def seed_if_empty(
        self,
        seed_path: str | Path,
        *,
        bcrypt_rounds: int = 10,
    ) -> None:

        with self._connect() as conn:
            conn.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                ("minilms:seed:" + self.schema,),
            )
            count = conn.execute("SELECT COUNT(*) AS n FROM users").fetchone()["n"]

            if count:
                return

            payload: dict[str, Any] = json.loads(
                Path(seed_path).read_text(encoding="utf-8")
            )

            # Seed users
            for row in payload.get("users", []):
                conn.execute(
                    """
                    INSERT INTO users (
                        id,
                        email,
                        role,
                        password_hash,
                        token_version
                    )
                    VALUES (%s, %s, %s, %s, 0)
                    """,
                    (
                        str(row["id"]),
                        str(row["email"]).lower(),
                        str(row["role"]).upper(),
                        hash_password(
                            str(row["password"]),
                            rounds=bcrypt_rounds,
                        ),
                    ),
                )

            # Seed courses
            for row in payload.get("courses", []):
                conn.execute(
                    """
                    INSERT INTO courses (
                        id,
                        title,
                        instructor_id
                    )
                    VALUES (%s, %s, %s)
                    """,
                    (
                        str(row["id"]),
                        str(row["title"]),
                        str(row["instructorId"]),
                    ),
                )

            # Seed enrollments
            for row in payload.get("enrollments", []):
                conn.execute(
                    """
                    INSERT INTO enrollments (
                        course_id,
                        student_id,
                        score
                    )
                    VALUES (%s, %s, %s)
                    """,
                    (
                        str(row["courseId"]),
                        str(row["studentId"]),
                        float(row["score"]),
                    ),
                )

