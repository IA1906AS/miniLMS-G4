    def set_score(
        self,
        course_id: str,
        student_id: str,
        score: float,
        expected_version: int,
    ) -> int | None:

        with self._connect() as conn:
            row = conn.execute(
                """
                UPDATE enrollments
                SET score = %s, version = version + 1
                WHERE course_id = %s
                AND student_id = %s
                AND version = %s
                RETURNING version
                """,
                (
                    score,
                    course_id,
                    student_id,
                    expected_version,
                ),
            ).fetchone()
        return row["version"] if row else None

