    # ========================================================
    # LOGIN ATTEMPTS
    # ========================================================

    def get_attempt(
        self,
        email: str,
    ) -> LoginAttempt:

        with self._connect() as conn:
            row = conn.execute(
                """
                SELECT *
                FROM attempts
                WHERE email = %s
                """,
                (email.strip().lower(),),
            ).fetchone()

        if row is None:
            return LoginAttempt()

        return LoginAttempt(
            failures=int(row["failures"]),
            locked_until=float(row["locked_until"]),
        )

    def save_attempt(
        self,
        email: str,
        attempt: LoginAttempt,
    ) -> None:

        with self._connect() as conn:
            conn.execute(
                """
                INSERT INTO attempts (
                    email,
                    failures,
                    locked_until
                )
                VALUES (%s, %s, %s)

                ON CONFLICT(email)
                DO UPDATE SET
                    failures = excluded.failures,
                    locked_until = excluded.locked_until
                """,
                (
                    email.strip().lower(),
                    attempt.failures,
                    attempt.locked_until,
                ),
            )

    # ========================================================
    # JWT REVOCATION
    # ========================================================

    def revoke_token(self, jti: str, expires_at: int) -> None:
        """Persist a revoked JWT until its expiration."""
        with self._connect() as conn:
            conn.execute(
                "DELETE FROM revoked_jwts WHERE expires_at <= %s", (int(time.time()),)
            )
            conn.execute(
                "INSERT INTO revoked_jwts (jti, expires_at) VALUES (%s, %s) ON CONFLICT (jti) DO NOTHING",
                (jti, expires_at),
            )

    def is_token_revoked(self, jti: str) -> bool:
        """Return whether an unexpired revoked JWT exists."""
        with self._connect() as conn:
            conn.execute(
                "DELETE FROM revoked_jwts WHERE expires_at <= %s", (int(time.time()),)
            )
            row = conn.execute(
                "SELECT 1 FROM revoked_jwts WHERE jti = %s", (jti,)
            ).fetchone()
        return row is not None

    # ========================================================
    # RESET TOKENS
    # ========================================================

    def add_reset_token(
        self,
        token: str,
        user_id: str,
        ttl_seconds: int,
    ) -> ResetToken:

        expires_at = time.time() + ttl_seconds

        with self._connect() as conn:
            conn.execute(
                """
                INSERT INTO reset_tokens (
                    token,
                    user_id,
                    expires_at
                )
                VALUES (%s, %s, %s)
                """,
                (
                    token,
                    user_id,
                    expires_at,
                ),
            )

        return ResetToken(
            token=token,
            user_id=user_id,
            expires_at=expires_at,
        )

    def take_reset_token(
        self,
        token: str,
    ) -> ResetToken | None:

        with self._connect() as conn:
            row = conn.execute(
                """
                SELECT *
                FROM reset_tokens
                WHERE token = %s
                FOR UPDATE
                """,
                (token,),
            ).fetchone()

            if row is None:
                return None

            conn.execute(
                "DELETE FROM reset_tokens WHERE token = %s",
                (token,),
            )

        item = ResetToken(
            token=row["token"],
            user_id=row["user_id"],
            expires_at=float(row["expires_at"]),
        )

        if item.expires_at < time.time():
            return None

        return item


