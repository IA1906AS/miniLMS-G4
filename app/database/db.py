    def find_user_by_email(
        self,
        email: str,
    ) -> User | None:

        with self._connect() as conn:
            row = conn.execute(
                "SELECT * FROM users WHERE email = %s",
                (email.strip().lower(),),
            ).fetchone()

        return _user(row) if row else None

    def get_fallback_password_hash(self) -> str:

        with self._connect() as conn:
            row = conn.execute(
                """
                SELECT password_hash
                FROM users
                ORDER BY id
                LIMIT 1
                """
            ).fetchone()

        if row is None:
            raise RuntimeError("PostgreSQL store has no users; seed the database first")

        return str(row["password_hash"])

    def get_user(
        self,
        user_id: str,
    ) -> User | None:

        with self._connect() as conn:
            row = conn.execute(
                "SELECT * FROM users WHERE id = %s",
                (user_id,),
            ).fetchone()

        return _user(row) if row else None

    def update_profile(self, user_id: str, changes: dict[str, str]) -> User:
        """Update allowed profile fields and return the previous record atomically."""
        allowed = {"full_name", "bio", "contact", "avatar_filename"}
        if not changes or set(changes) - allowed:
            raise ValueError("Invalid profile fields")
        with self._connect() as conn:
            row = conn.execute(
                "SELECT * FROM users WHERE id = %s FOR UPDATE", (user_id,)
            ).fetchone()
            if row is None:
                raise ValueError("Unknown user")
            assignments = ", ".join(f"{key} = %s" for key in changes)
            conn.execute(
                f"UPDATE users SET {assignments} WHERE id = %s",
                (*changes.values(), user_id),
            )
        return _user(row)

    def add_user(
        self,
        email: str,
        password_hash: str,
        role: str,
    ) -> User:
        """Create a user with a collision-resistant ID."""

        import uuid

        user_id = f"u{uuid.uuid4().hex}"
        normalized_email = email.strip().lower()

        with self._connect() as conn:
            conn.execute(
                """
                INSERT INTO users (
                    id,
                    email,
                    role,
                    password_hash,
                    token_version
                )
                VALUES (%s, %s, %s, %s, 0)
                """,
                (
                    user_id,
                    normalized_email,
                    role.upper(),
                    password_hash,
                ),
            )

        return User(
            id=user_id,
            email=normalized_email,
            role=role.upper(),
            password_hash=password_hash,
            token_version=0,
        )

    # ========================================================
    # PASSWORD RESET + JWT INVALIDATION
    # ========================================================

    def update_password(
        self,
        user_id: str,
        password_hash: str,
    ) -> None:

        with self._connect() as conn:
            cursor = conn.execute(
                """
                UPDATE users
                SET password_hash = %s,
                    token_version = token_version + 1
                WHERE id = %s
                """,
                (
                    password_hash,
                    user_id,
                ),
            )

            if cursor.rowcount != 1:
                raise ValueError("User not found")

    def change_password_atomic(
        self, user_id: str, old_hash: str, new_hash: str
    ) -> bool:
        """Replace the verified password and invalidate sessions and reset links."""
        with self._connect() as conn:
            cursor = conn.execute(
                "UPDATE users SET password_hash = %s, token_version = token_version + 1 "
                "WHERE id = %s AND password_hash = %s",
                (new_hash, user_id, old_hash),
            )
            if cursor.rowcount != 1:
                return False
            conn.execute("DELETE FROM reset_tokens WHERE user_id = %s", (user_id,))
            return True

    def search_users(self, query: str, limit: int, offset: int):
        with self._connect() as conn:
            params = (query, query, query)
            where = "WHERE strpos(lower(id), lower(%s)) > 0 OR strpos(lower(email), lower(%s)) > 0 OR strpos(lower(full_name), lower(%s)) > 0"
            total = conn.execute(
                "SELECT count(*) AS n FROM users " + where, params
            ).fetchone()["n"]
            rows = conn.execute(
                "SELECT * FROM users "
                + where
                + " ORDER BY lower(email), id LIMIT %s OFFSET %s",
                (*params, limit, offset),
            ).fetchall()
            return [_user(row) for row in rows], total

    def administer_user(self, actor_id: str, user_id: str, changes: dict):
        from app.api.errors import Forbidden, NotFound, UserUpdateConflict

        with self._connect() as conn:
            # Serialize administration across workers, then recheck the actor.
            conn.execute(
                "SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                ("minilms:users:" + self.schema,),
            )
            actor = conn.execute(
                "SELECT * FROM users WHERE id = %s FOR UPDATE", (actor_id,)
            ).fetchone()
            if actor is None or actor["role"] != "ADMIN" or actor["is_locked"]:
                raise Forbidden()
            target = conn.execute(
                "SELECT * FROM users WHERE id = %s FOR UPDATE", (user_id,)
            ).fetchone()
            if target is None:
                raise NotFound()
            role = changes.get("role", target["role"])
            locked = changes.get("isLocked", target["is_locked"])
            if actor_id == user_id and (role != "ADMIN" or locked):
                raise UserUpdateConflict("SELF_ADMIN_CHANGE")
            if (
                role != "INSTRUCTOR"
                and target["role"] == "INSTRUCTOR"
                and conn.execute(
                    "SELECT 1 FROM courses WHERE instructor_id = %s LIMIT 1", (user_id,)
                ).fetchone()
            ):
                raise UserUpdateConflict("INSTRUCTOR_HAS_COURSES")
            if role != target["role"] or locked != target["is_locked"]:
                conn.execute(
                    "UPDATE users SET role = %s, is_locked = %s, token_version = token_version + 1 WHERE id = %s",
                    (role, locked, user_id),
                )
                conn.execute("DELETE FROM reset_tokens WHERE user_id = %s", (user_id,))
            row = conn.execute(
                "SELECT * FROM users WHERE id = %s", (user_id,)
            ).fetchone()
            return _user(row)

    def reset_password_atomic(
        self,
        token_hash: str,
        password_hash: str,
    ) -> str | None:
        """Atomically reset password and consume reset token."""

        with self._connect() as conn:
            # Lock the token row until password update and token deletion commit.

            row = conn.execute(
                """
                SELECT user_id
                FROM reset_tokens
                WHERE token = %s
                  AND expires_at > %s
                FOR UPDATE
                """,
                (token_hash, time.time()),
            ).fetchone()

            if row is None:
                return None

            user_id = str(row["user_id"])

            cursor = conn.execute(
                """
                UPDATE users
                SET password_hash = %s,
                    token_version = token_version + 1
                WHERE id = %s
                """,
                (password_hash, user_id),
            )

            if cursor.rowcount != 1:
                raise ValueError("Reset token references missing user")

            cursor = conn.execute(
                "DELETE FROM reset_tokens WHERE token = %s",
                (token_hash,),
            )

            if cursor.rowcount != 1:
                raise RuntimeError("Failed to consume reset token")

            return user_id

