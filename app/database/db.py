def build_postgres_store(
    database_url: str,
    schema: str = "public",
    *,
    seed_path: str | Path,
    bcrypt_rounds: int = 10,
) -> PostgresStore:

    store = PostgresStore(database_url, schema=schema)

    store.seed_if_empty(
        seed_path,
        bcrypt_rounds=bcrypt_rounds,
    )

    return store
